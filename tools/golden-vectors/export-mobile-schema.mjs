#!/usr/bin/env node
/**
 * Dumps packages/db/src/index.ts's `AppSchema` (the PowerSync client schema)
 * to tools/golden-vectors/vectors/mobile-schema.json — the source of truth
 * that gen-mobile-schema.mjs renders into PocketCareSchema.kt/.swift.
 *
 * Why introspect at runtime instead of hand-transcribing 63 tables: every
 * PowerSync table implicitly gets an `id: TEXT` primary key whether or not
 * it's redeclared in the table's column map (most tables omit it; a few,
 * like `profiles`, redeclare it redundantly) — a per-table inconsistency
 * that's easy to get wrong by eye across 63 tables and trivial to capture
 * exactly by asking the real `Table` objects what they think their own
 * columns are (`table.toJSON()`).
 *
 * index.ts's own last ~15 lines re-export `SupabaseConnector` etc. from
 * ./connector.ts, which uses TS parameter-property syntax that
 * `node --experimental-strip-types` (strip-only mode) can't parse. Those
 * re-exports are irrelevant to the schema, so this script imports a copy of
 * index.ts with everything from the trailing `export { SupabaseConnector` ...
 * `from "./auth.ts";` block removed, rather than the file itself.
 *
 * Run: node tools/golden-vectors/export-mobile-schema.mjs
 */
import { readFileSync, writeFileSync, unlinkSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const dbSrcDir = path.join(repoRoot, "packages", "db", "src");
const indexTsPath = path.join(dbSrcDir, "index.ts");
const outJsonPath = path.join(repoRoot, "tools", "golden-vectors", "vectors", "mobile-schema.json");

const source = readFileSync(indexTsPath, "utf8");
const marker = "\nexport {\n  SupabaseConnector,";
const cut = source.indexOf(marker);
if (cut === -1) {
  throw new Error(
    "export-mobile-schema.mjs: couldn't find the trailing connector/quarantine/auth re-export " +
      "block in packages/db/src/index.ts (looked for 'export {\\n  SupabaseConnector,'). " +
      "The file's shape changed — update this script's marker to match.",
  );
}
const schemaOnlySource = source.slice(0, cut) + "\n";

// Written next to index.ts (not /tmp) so its bare `@powersync/common` import
// resolves via the repo's normal node_modules walk-up.
const tempPath = path.join(dbSrcDir, "__schema_export_temp__.ts");
writeFileSync(tempPath, schemaOnlySource, "utf8");

let AppSchema;
try {
  ({ AppSchema } = await import(`${tempPath}?t=${Date.now()}`));
} finally {
  unlinkSync(tempPath);
}

const tables = AppSchema.tables
  .map((t) => t.toJSON())
  .map((t) => ({
    name: t.name,
    view_name: t.view_name,
    // Every PowerSync table has an implicit `id: TEXT` primary key. Some
    // table definitions in index.ts redeclare it in their column map
    // (harmless duplicate); most don't. Record whether this one did, so the
    // codegen step can decide whether to emit it once or twice — it emits
    // it exactly once either way, but the flag makes that explicit rather
    // than silently deduping.
    id_declared_explicitly: t.columns.some((c) => c.name === "id"),
    columns: t.columns.filter((c) => c.name !== "id").map((c) => ({ name: c.name, type: c.type })),
    indexes: t.indexes.map((idx) => ({
      name: idx.name,
      columns: idx.columns.map((c) => ({ name: c.name, ascending: c.ascending, type: c.type })),
    })),
    local_only: t.local_only,
    insert_only: t.insert_only,
  }))
  .sort((a, b) => a.name.localeCompare(b.name));

const dump = {
  _comment:
    "GENERATED by tools/golden-vectors/export-mobile-schema.mjs from packages/db/src/index.ts's " +
    "AppSchema. Do not hand-edit. Every table additionally has an implicit `id: TEXT` primary " +
    "key managed by PowerSync (not listed in `columns`, per id_declared_explicitly above).",
  table_count: tables.length,
  tables,
};

writeFileSync(outJsonPath, JSON.stringify(dump, null, 2) + "\n", "utf8");
console.log(`Wrote ${tables.length} tables to ${path.relative(repoRoot, outJsonPath)}`);
