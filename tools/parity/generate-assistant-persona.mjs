#!/usr/bin/env node
/**
 * tools/parity/generate-assistant-persona.mjs
 *
 * apps/web/src/assistant/AssistantChat.tsx's PERSONA -> AssistantPersona.kt / .swift.
 *
 * WHY GENERATED, and this one matters more than the tool descriptions did.
 * PERSONA is ~40 lines of system prompt: the assistant's voice, its refusal
 * scope, the exact `<ui>` card grammar it may emit, the route list it is allowed
 * to link to, and the rule separating a TOOL CALL from a NAVIGATION LINK. Every
 * one of those is behaviour.
 *
 * A hand-copy would drift the first time someone reflowed a paragraph, and the
 * failure would be invisible: the phone's assistant would decline something the
 * browser's answers, or call a tool where the browser links. Nobody would
 * attribute that to a transcription.
 *
 * It is emitted as ONE string constant, joined with "\n" exactly as web joins
 * its array, so the bytes that reach the model are identical.
 *
 * Usage: node tools/parity/generate-assistant-persona.mjs
 */

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = process.env.SANVYA_REPO_ROOT
  ? path.resolve(process.env.SANVYA_REPO_ROOT)
  : path.resolve(__dirname, "../..");

const SRC = path.join(REPO_ROOT, "apps/web/src/assistant/AssistantChat.tsx");
const KT_OUT = path.join(
  REPO_ROOT,
  "apps/android/domain/src/main/kotlin/com/sanvya/app/domain/assistant/AssistantPersona.kt",
);
const SWIFT_OUT = path.join(REPO_ROOT, "apps/ios/Domain/Sources/Domain/AssistantPersona.swift");

const src = readFileSync(SRC, "utf8");
const start = src.indexOf("const PERSONA = [");
if (start < 0) throw new Error("PERSONA not found in AssistantChat.tsx");
const open = src.indexOf("[", start);
let depth = 0;
let end = open;
for (; end < src.length; end++) {
  if (src[end] === "[") depth++;
  else if (src[end] === "]") {
    depth--;
    if (depth === 0) break;
  }
}
// eslint-disable-next-line no-eval
const lines = eval(src.slice(open, end + 1));
const persona = lines.join("\n");

/** Kotlin needs `$` escaped; both need the same five other escapes. */
const ktLit = (s) =>
  s
    .replace(/\\/g, "\\\\")
    .replace(/"/g, '\\"')
    .replace(/\$/g, "\\$")
    .replace(/\r/g, "\\r")
    .replace(/\t/g, "\\t");

const swiftLit = (s) =>
  s.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\r/g, "\\r").replace(/\t/g, "\\t");

const header = (mirror) => `// GENERATED by tools/parity/generate-assistant-persona.mjs -- do not edit.
// Source: apps/web/src/assistant/AssistantChat.tsx (PERSONA).
//
// The assistant's system prompt: its voice, its refusal scope, the \`<ui>\` card
// grammar it may emit, the routes it may link to, and the rule separating a TOOL
// CALL from a NAVIGATION LINK. All of that is BEHAVIOUR, not documentation --
// a reflowed paragraph on one platform is a different assistant, and nobody
// would attribute that to a transcription.
//
// Deliberately English on every platform: this is the model's instruction, not
// the user's interface. Web says the same in its own comment.
//
// Mirrors ${mirror}.`;

const ktLines = persona.split("\n").map((l) => `    "${ktLit(l)}",`).join("\n");
const swiftLines = persona.split("\n").map((l) => `    "${swiftLit(l)}",`).join("\n");

writeFileSync(
  KT_OUT,
  `${header("iOS's AssistantPersona.swift")}

package com.sanvya.app.domain.assistant

/** Joined with newlines, exactly as web joins its array. */
private val PERSONA_LINES = listOf(
${ktLines}
)

/**
 * The system prompt, as one string.
 *
 * Web sends it as a cacheable system block, and so should every caller here:
 * it is identical on every request, which is the whole reason it is a separate
 * block rather than part of the first message.
 */
val ASSISTANT_PERSONA: String = PERSONA_LINES.joinToString("\\n")
`,
);

writeFileSync(
  SWIFT_OUT,
  `${header("Android's AssistantPersona.kt")}

import Foundation

/// Joined with newlines, exactly as web joins its array.
private let personaLines: [String] = [
${swiftLines}
]

/**
 The system prompt, as one string.

 Web sends it as a cacheable system block, and so should every caller here: it is
 identical on every request, which is the whole reason it is a separate block
 rather than part of the first message.
 */
public let assistantPersona: String = personaLines.joined(separator: "\\n")
`,
);

console.log(
  `assistant-persona: ${persona.split("\n").length} lines, ${persona.length} chars -> ` +
    `${path.relative(REPO_ROOT, KT_OUT)}, ${path.relative(REPO_ROOT, SWIFT_OUT)}`,
);
