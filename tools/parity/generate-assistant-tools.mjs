#!/usr/bin/env node
/**
 * tools/parity/generate-assistant-tools.mjs
 *
 * apps/web/src/assistant/tools.ts's ASSISTANT_TOOLS -> AssistantTools.kt / .swift.
 *
 * WHY GENERATED. This is the tool surface the model is handed: seven names,
 * their descriptions, and a JSON Schema each. It is DATA, and hand-copying data
 * into two languages is how the browser ends up offering a tool the phones do
 * not, or describing it differently enough that the model behaves differently.
 * The descriptions in particular are prompt text -- "Use sparingly -- not
 * one-off details" is doing real work, and a paraphrase is a behaviour change.
 *
 * The schemas are emitted as JSON STRING literals rather than as native
 * structures, because that is what goes over the wire: the request body carries
 * `input_schema` verbatim, so building a typed tree on each platform only to
 * re-serialise it would add two chances to differ and buy nothing.
 *
 * Usage: node tools/parity/generate-assistant-tools.mjs
 */

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = process.env.SANVYA_REPO_ROOT
  ? path.resolve(process.env.SANVYA_REPO_ROOT)
  : path.resolve(__dirname, "../..");

const SRC = path.join(REPO_ROOT, "apps/web/src/assistant/tools.ts");
const KT_OUT = path.join(
  REPO_ROOT,
  "apps/android/domain/src/main/kotlin/com/sanvya/app/domain/assistant/AssistantTools.kt",
);
const SWIFT_OUT = path.join(REPO_ROOT, "apps/ios/Domain/Sources/Domain/AssistantTools.swift");

/**
 * Read the array literal out of the source and evaluate it.
 *
 * `eval` on a slice of our own repo, in a build script, with no input from
 * anywhere else. The alternative -- a regex over seven nested schemas -- would
 * be the fragile option, not the safe one.
 */
function readTools() {
  const src = readFileSync(SRC, "utf8");
  const start = src.indexOf("export const ASSISTANT_TOOLS = [");
  if (start < 0) throw new Error("ASSISTANT_TOOLS not found in tools.ts");
  const open = src.indexOf("[", start);
  let depth = 0;
  let end = open;
  for (; end < src.length; end++) {
    if (src[end] === "[") depth++;
    else if (src[end] === "]") {
      depth--;
      if (depth === 0) break;
    }
  }
  const literal = src.slice(open, end + 1);
  // eslint-disable-next-line no-eval
  return eval(literal);
}

/** The confirm set, read from the source rather than restated here. */
function readConfirmSet(src) {
  const m = src.match(/const CONFIRM_TOOLS = new Set\((\[[\s\S]*?\])\)/);
  if (!m) throw new Error("CONFIRM_TOOLS not found in tools.ts");
  // eslint-disable-next-line no-eval
  return eval(m[1]);
}

const tools = readTools();
const src = readFileSync(SRC, "utf8");
const confirm = readConfirmSet(src);

/** A Kotlin/Swift string literal: both escape the same five things the same way. */
const lit = (s) =>
  '"' +
  s
    .replace(/\\/g, "\\\\")
    .replace(/"/g, '\\"')
    .replace(/\n/g, "\\n")
    .replace(/\r/g, "\\r")
    .replace(/\t/g, "\\t")
    .replace(/\$/g, "\\$") +
  '"';

/** Swift does not need `$` escaped and Kotlin does; everything else is shared. */
const swiftLit = (s) =>
  '"' +
  s.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, "\\n").replace(/\r/g, "\\r").replace(/\t/g, "\\t") +
  '"';

const header = (mirror) => `// GENERATED by tools/parity/generate-assistant-tools.mjs -- do not edit.
// Source: apps/web/src/assistant/tools.ts (ASSISTANT_TOOLS + CONFIRM_TOOLS).
//
// The tool surface the assistant model is handed. Descriptions are PROMPT TEXT,
// not documentation: paraphrasing one changes how the model behaves, which is
// why this file is generated from web's array rather than transcribed.
//
// Mirrors ${mirror}.`;

const ktBody = `${header("iOS's AssistantTools.swift")}

package com.sanvya.app.domain.assistant

/** One tool the model may call. [inputSchema] is JSON, verbatim, ready to send. */
data class AssistantTool(
    val name: String,
    val description: String,
    val inputSchema: String,
    /**
     * Whether a call has to be confirmed by the user before it runs.
     *
     * Every financial WRITE is true. \`remember\` is the only false one, and web
     * says why in its own description: it "runs silently, no confirmation".
     */
    val needsConfirm: Boolean,
)

val ASSISTANT_TOOLS: List<AssistantTool> = listOf(
${tools
  .map(
    (t) => `    AssistantTool(
        name = ${lit(t.name)},
        description = ${lit(t.description)},
        inputSchema = ${lit(JSON.stringify(t.input_schema))},
        needsConfirm = ${confirm.includes(t.name)},
    ),`,
  )
  .join("\n")}
)

/** True when a call must be confirmed. Unknown names are NOT confirmed, matching web's Set lookup. */
fun assistantToolNeedsConfirm(name: String): Boolean =
    ASSISTANT_TOOLS.any { it.name == name && it.needsConfirm }
`;

const swiftBody = `${header("Android's AssistantTools.kt")}

import Foundation

/// One tool the model may call. \`inputSchema\` is JSON, verbatim, ready to send.
public struct AssistantTool: Equatable, Sendable {
    public let name: String
    public let description: String
    public let inputSchema: String
    /// Whether a call has to be confirmed by the user before it runs.
    ///
    /// Every financial WRITE is true. \`remember\` is the only false one, and web
    /// says why in its own description: it "runs silently, no confirmation".
    public let needsConfirm: Bool
}

public let assistantTools: [AssistantTool] = [
${tools
  .map(
    (t) => `    AssistantTool(
        name: ${swiftLit(t.name)},
        description: ${swiftLit(t.description)},
        inputSchema: ${swiftLit(JSON.stringify(t.input_schema))},
        needsConfirm: ${confirm.includes(t.name)}
    ),`,
  )
  .join("\n")}
]

/// True when a call must be confirmed. Unknown names are NOT confirmed, matching web's Set lookup.
public func assistantToolNeedsConfirm(_ name: String) -> Bool {
    assistantTools.contains { $0.name == name && $0.needsConfirm }
}
`;

writeFileSync(KT_OUT, ktBody);
writeFileSync(SWIFT_OUT, swiftBody);
console.log(
  `assistant-tools: ${tools.length} tools, ${confirm.length} requiring confirmation -> ` +
    `${path.relative(REPO_ROOT, KT_OUT)}, ${path.relative(REPO_ROOT, SWIFT_OUT)}`,
);
